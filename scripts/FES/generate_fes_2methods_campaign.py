"""Generate the FES two-method campaign scenario matrix.

2 demand methods (espeni | component) x 4 FES2025 pathways x 3 years (2030/40/50)
x 41 weather years (1985-2025) = 984 Reduced-network, full-year, two-stage
(wholesale + Balancing Mechanism) scenarios.

Writes config/scenarios.d/fes_2methods_campaign.yaml (merged by config_loader)
and myriad/fes2methods_scenario_names.txt (the task list for the array job).

Scenario id: {HT|EE|HE|FB}{30|40|50}_{esp|cmp}_w{YYYY}
"""
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PATHWAYS = {"HT": "Holistic Transition", "EE": "Electric Engagement",
            "HE": "Hydrogen Evolution", "FB": "Falling Behind"}
YEARS = {"30": 2030, "40": 2040, "50": 2050}
METHODS = {"esp": "espeni", "cmp": "component"}
WEATHER_YEARS = list(range(1985, 2026))   # 1985-2025 inclusive (41)

BLOCK = """{sid}:
  description: "FES2025 {pname} {year} - Reduced full-year two-stage market (wholesale+BM), {mname} demand, weather {wy}"
  modelled_year: {year}
  FES_year: 2025
  FES_scenario: "{pname}"
  renewables_year: {wy}
  demand_year: {wy}
  demand_timeseries: "{mname}"
  network_model: "Reduced"
  component_aggregation:
    enabled: true
    include_generators: true
    include_storage_units: true
    include_loads: true
  renewable_aggregation:
    enabled: true
  market:
    enabled: true
    wholesale:
      mode: "rolling_day_ahead"
      window_hours: 24
      carry_soc: true
    balancing:
      mode: "rolling"
      window_hours: 24
"""

def main():
    out_yaml = REPO / "config" / "scenarios.d" / "fes_2methods_campaign.yaml"
    out_yaml.parent.mkdir(parents=True, exist_ok=True)
    names, blocks = [], []
    for mcode, mname in METHODS.items():
        for pcode, pname in PATHWAYS.items():
            for ycode, year in YEARS.items():
                for wy in WEATHER_YEARS:
                    sid = f"{pcode}{ycode}_{mcode}_w{wy}"
                    names.append(sid)
                    blocks.append(BLOCK.format(sid=sid, pname=pname, year=year,
                                               wy=wy, mname=mname))
    header = ("# AUTO-GENERATED by scripts/FES/generate_fes_2methods_campaign.py\n"
              f"# {len(names)} scenarios = 2 methods x 4 pathways x 3 years x "
              f"{len(WEATHER_YEARS)} weather years.\n"
              "# Two-stage market+BM, Reduced network, full year. Do not hand-edit.\n\n")
    out_yaml.write_text(header + "\n".join(blocks), encoding="utf-8", newline="\n")
    (REPO / "myriad" / "fes2methods_scenario_names.txt").write_text(
        "\n".join(names) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out_yaml}  ({len(names)} scenarios)")
    print(f"wrote {REPO/'myriad'/'fes2methods_scenario_names.txt'}")
    # quick breakdown
    for m in METHODS: print(f"  {m}: {sum(1 for n in names if f'_{m}_' in n)}")

if __name__ == "__main__":
    main()
